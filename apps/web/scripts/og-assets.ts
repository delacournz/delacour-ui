#!/usr/bin/env bun
/**
 * Writes what the social card route needs and cannot make for itself:
 *
 *     bun run og-assets
 *
 * - `src/og/heroes.ts` — each docs page's hero, and a lazy import of every
 *   capture a card can stand in its phone.
 * - `src/og/frames/<id>.png` — for a device clip, the frame `MOMENTS` names,
 *   cut from the committed dark clip.
 *
 * Both are committed. The server has no `ffmpeg` and no `content/`, so neither
 * can be worked out at request time. Run it after `bun run previews` recaptures
 * a device hero, and after a docs page gains, loses or changes its first
 * `<Preview>`; `src/og/page.test.ts` fails by name until you do.
 */

import { mkdir, rm } from "node:fs/promises";
import { dirname, join } from "node:path";
import { $ } from "bun";
import { readPages } from "@/og/content";
import { capturePath, isFramed, MOMENTS, PRODUCT_HERO } from "@/og/page";
import { type PreviewEntry, type PreviewId, previews } from "@/previews/manifest";

const WEB = join(import.meta.dir, "..");
const FRAMES = join(WEB, "src/og/frames");
const HEROES = join(WEB, "src/og/heroes.ts");

async function cut(id: PreviewId): Promise<void> {
	const entry: PreviewEntry = previews[id];
	const moment = MOMENTS[id];
	if (!moment || !entry.dark.video || !entry.durationMs) throw new Error(`${id} has no clip to cut a frame from`);

	const out = join(WEB, capturePath(id));
	const video = join(WEB, "public", entry.dark.video.replace(/\?.*$/, ""));
	const seconds = ((entry.durationMs * moment.at) / 1000).toFixed(3);

	await mkdir(dirname(out), { recursive: true });
	const result =
		await $`ffmpeg -y -hide_banner -loglevel error -ss ${seconds} -i ${video} -frames:v 1 -compression_level 100 ${out}`
			.quiet()
			.nothrow();
	if (result.exitCode !== 0) throw new Error(`ffmpeg could not cut ${id} at ${seconds}s:\n${result.stderr.toString()}`);
}

const pages = (await readPages()).filter((page) => page.hero);
const ids = [
	...new Set<PreviewId>([...pages.flatMap((page) => page.hero ?? []), ...Object.values(PRODUCT_HERO)]),
].sort();

for (const id of ids) {
	if (previews[id].frame === "device" && !MOMENTS[id])
		throw new Error(`${id} is a device clip with no entry in MOMENTS`);
}

await rm(FRAMES, { recursive: true, force: true });
for (const id of ids.filter(isFramed)) await cut(id);

const heroLines = pages.map((page) => `\t${JSON.stringify(page.key)}: ${JSON.stringify(page.hero)},`);
const captureLines = ids.map((id) => {
	const from = capturePath(id).startsWith("src/og/")
		? `./${capturePath(id).slice("src/og/".length)}`
		: `../../${capturePath(id)}`;
	const cutAt = isFramed(id) ? `cut: ${JSON.stringify(previews[id].sourceHash)}, ` : "";
	return `\t${JSON.stringify(id)}: { ${cutAt}load: () => import(${JSON.stringify(`${from}?inline`)}) },`;
});

await Bun.write(
	HEROES,
	`// Generated by apps/web/scripts/og-assets.ts. Do not edit.
//
// Regenerate with \`bun run og-assets\` in apps/web, after a device hero is
// recaptured or a docs page's first \`<Preview>\` changes.

import type { PreviewId } from "@/previews/manifest";
import type { Capture } from "./page";

/** Each docs page's hero, keyed by its slugs. A page that is absent has none. */
export const pageHeroes: Readonly<Record<string, PreviewId>> = {
${heroLines.join("\n")}
};

/** Every capture a card can stand in its phone: the heroes above and each product's default. */
export const captures: Readonly<Partial<Record<PreviewId, Capture>>> = {
${captureLines.join("\n")}
};
`
);
await $`bunx biome format --write ${HEROES}`.quiet();

console.log(`${pages.length} heroes, ${ids.length} captures, ${ids.filter(isFramed).length} frames cut → src/og/`);
